#!/usr/bin/env python3
"""Build the pump shotgun, fitted mittens, and every existing held pose."""
from __future__ import annotations
import argparse
import hashlib
import json
from pathlib import Path
import numpy as np
from asset_sources import source_bytes
from md2_assets import MD2
from build_m16 import (atlas_uvs, encode_md2, rigid_transforms,
                       texture_bytes as shared_texture_bytes)
from build_soldier_height import transform_model, CONFIG as HEIGHT_CONFIG
from shotgun_geometry import build_shotgun, GRIP, pump_fractions, PUMP_TRAVEL

ROOT = Path(__file__).resolve().parents[2]
BASE = ROOT / 'baseq2'
MANIFEST = ROOT / 'tools/assets/shotgun-manifest.json'
ADS_HEADER = ROOT / 'src/client/header/shotgun_model_ads.h'
MODELS = {'models/weapons/g_shotg/tris.md2':'pickup',
          'models/weapons/v_shotg/tris.md2':'view',
          'players/soldier/w_shotgun.md2':'player',
          'models/monsters/soldier/weapon_shotgun.md2':'enemy'}
TEXTURES = ('models/weapons/g_shotg/skin.png','models/weapons/v_shotg/skin.png')
BASELINES = {'view':{'triangles':1399,'position_vertices':700,'frames':1,'file_bytes':55136},
             'pickup':{'triangles':799,'position_vertices':400,'frames':1,'file_bytes':33004},
             'player':{'triangles':1399,'position_vertices':700,'frames':198,'file_bytes':615336},
             'enemy':{'triangles':1399,'position_vertices':700,'frames':475,'file_bytes':1401944}}
DEPENDENCIES = ('build_shotgun.py','shotgun_geometry.py','build_m16.py','m16_geometry.py')


def sha(data):
    return hashlib.sha256(data).hexdigest()


def texture_bytes():
    """Shared molded plastic, with painted pump grooves and mitten fingers."""
    return shared_texture_bytes()


def placement(role):
    rotation = np.eye(3)
    if role == 'view':
        # Same arm scale as the rifle, with the receiver slightly further back.
        scale = (56.49812462925911 + 9.061456233263016) / 100
        offset = np.array([-13.5, -8.5, -8.6])
    elif role == 'pickup':
        scale = .58
        rotation = np.diag([-1.,-1.,1.])
        offset = np.array([29.,0.,16.9])
    else:
        # Retain the original grip attachment point; pose the longer barrel
        # rigidly with the archived weapon, then articulate only the fore-end.
        scale = .245
        offset = np.array([10.2,-4.75,12.8])-np.asarray(GRIP)*scale
    return rotation * scale, offset, rotation


def ads_header(anchors):
    rear, muzzle = anchors['rear_sight'], anchors['muzzle']
    return ('''/* Generated by tools/assets/build_shotgun.py; model units only. */
#ifndef PP_SHOTGUN_MODEL_ADS_H
#define PP_SHOTGUN_MODEL_ADS_H
#define PP_SHOTGUN_ADS_FORWARD (%sf)
#define PP_SHOTGUN_ADS_RIGHT (%sf)
#define PP_SHOTGUN_ADS_UP (%sf)
#define PP_SHOTGUN_MUZZLE_FORWARD (%sf)
#define PP_SHOTGUN_MUZZLE_RIGHT (%sf)
#define PP_SHOTGUN_MUZZLE_UP (%sf)
#endif
''' % tuple(f'{v:.8f}' for v in (9.5-rear[0],rear[1],-rear[2],muzzle[0],-muzzle[1],muzzle[2]))).encode()


def build_assets():
    originals = json.loads((ROOT/'tools/assets/platoon-originals.json').read_text())
    meshes = {kind:build_shotgun(kind) for kind in ('world','view')}
    # Only a few distinct fore-end positions are needed across 713 poses.
    poses_by_amount = {(detail,amount):build_shotgun(detail,amount)
        for detail in ('world','view')
        for amount in set(pump_fractions('view',40)+pump_fractions('player',198)+pump_fractions('enemy',475))}
    atlas = texture_bytes()
    assets = {path:atlas for path in TEXTURES}
    manifest = dict(schema=1, generator='tools/assets/build_shotgun.py',
        dependencies_sha256={p:sha((ROOT/'tools/assets'/p).read_bytes()) for p in DEPENDENCIES},
        source_archive=originals['source_archive'], method='authored closed primitives; archived rigid poses',
        hand='M16 molded mittens; support hand and wrist follow the pump; elbow stays anchored',
        palette='M16 molded-plastic atlas; painted pump grooves and mitten creases', models=[],
        view_animation=dict(fire_frame=8, pump_fractions=pump_fractions('view',40),
                            pump_travel=PUMP_TRAVEL, cock_sound_delay=.2))
    for path, role in MODELS.items():
        source = None if role == 'pickup' else MD2.read(source_bytes(originals,'baseq2/'+path),source_compat=True)
        mesh = meshes['view' if role == 'view' else 'world']
        matrix, offset, rotation = placement(role)
        fit = None
        if role in ('player','enemy'):
            rotations, offsets, errors = rigid_transforms(source)
            names = source.names
            amounts = pump_fractions(role,len(names))
            positions, normal_poses = [], []
            for r,t,amount in zip(rotations,offsets,amounts):
                pose = poses_by_amount['world',amount]
                positions.append((np.asarray(pose['vertices']) @ matrix + offset) @ r + t)
                normal_poses.append(np.asarray(pose['normals']) @ rotation @ r)
            positions,normal_poses = np.asarray(positions),np.asarray(normal_poses)
            fit = dict(rms_max=float(f'{errors.max():.12g}'), frames=len(names))
        else:
            amounts = pump_fractions(role,40 if role=='view' else 1)
            poses = [poses_by_amount['view' if role=='view' else 'world',a] for a in amounts]
            positions = np.asarray([np.asarray(p['vertices']) @ matrix + offset for p in poses])
            normal_poses = np.asarray([np.asarray(p['normals']) @ rotation for p in poses])
            names = [f'shotgun_{i:02}' for i in range(40)] if role=='view' else ['frame_1']
        skin = TEXTURES[0] if role == 'pickup' else TEXTURES[1]
        raw, validation = encode_md2(positions, normal_poses, mesh['faces'],atlas_uvs(mesh),[skin],names)
        assets[path] = raw
        stats = MD2.read(raw).stats();stats.pop('frame_names')
        anchors = {name:(np.asarray(value) @ matrix + offset).tolist() for name,value in mesh['anchors'].items()}
        manifest['models'].append(dict(path=path, role=role, baseline=BASELINES.get(role), after=stats,
            pose_transfer=fit, validation=validation, anchors_frame0=anchors,
            pump_fractions=amounts, parts=mesh['parts']))
    normal = 'models/monsters/soldier/weapon_shotgun.md2'
    tall = 'models/monsters/soldier/tall/weapon_shotgun.md2'
    height = json.loads(HEIGHT_CONFIG.read_text())
    assets[tall] = transform_model(assets[normal],height['scale'],height['foot_z'])
    stats = MD2.read(assets[tall]).stats();stats.pop('frame_names')
    manifest['models'].append(dict(path=tall,role='enemy_tall',baseline=BASELINES['enemy'],after=stats))
    anchors = next(m['anchors_frame0'] for m in manifest['models'] if m['role']=='view')
    header = ads_header(anchors)
    manifest['ads_header'] = dict(path=ADS_HEADER.relative_to(ROOT).as_posix(),sha256=sha(header))
    manifest['files'] = [dict(path=p,bytes=len(raw),sha256=sha(raw)) for p,raw in sorted(assets.items())]
    return assets, manifest, header


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--verify',action='store_true')
    args = parser.parse_args()
    assets, manifest, header = build_assets()
    outputs = {BASE/p:raw for p,raw in assets.items()}
    outputs[MANIFEST] = (json.dumps(manifest,indent=2)+'\n').encode()
    outputs[ADS_HEADER] = header
    for path, raw in outputs.items():
        if args.verify:
            if not path.is_file() or path.read_bytes()!=raw:raise ValueError('Stale shotgun output: '+str(path))
        elif not path.is_file() or path.read_bytes()!=raw:
            path.parent.mkdir(parents=True,exist_ok=True);path.write_bytes(raw)
    for model in manifest['models']:
        print(f"{model['role']}: {model['after']['triangles']} triangles, {model['after']['frames']} frames")
    print('Verified shotgun' if args.verify else 'Built shotgun; regenerate colors, height, muzzle points and package')


if __name__=='__main__':main()
