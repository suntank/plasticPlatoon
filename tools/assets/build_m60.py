#!/usr/bin/env python3
"""Build the box-fed M60, existing mittens, and every existing held pose."""
from __future__ import annotations
import argparse
import hashlib
import json
from pathlib import Path
import numpy as np
from asset_sources import source_bytes
from md2_assets import MD2
from build_m16 import (atlas_uvs, encode_md2, rigid_transforms,
                       texture_bytes as shared_texture_bytes)
from m60_geometry import build_m60, GRIP
from build_soldier_height import transform_model, CONFIG as HEIGHT_CONFIG

ROOT = Path(__file__).resolve().parents[2]
BASE = ROOT / 'baseq2'
MANIFEST = ROOT / 'tools/assets/m60-manifest.json'
ADS_HEADER = ROOT / 'src/client/header/m60_model_ads.h'
HEAVY_MANIFEST = ROOT / 'tools/assets/heavy-gunner-manifest.json'
MODELS = {'models/weapons/g_chain/tris.md2':'pickup',
          'models/weapons/v_chain/tris.md2':'view',
          'players/soldier/w_chaingun.md2':'player',
          'models/monsters/soldier/weapon_heavy.md2':'enemy'}
TEXTURES = ('models/weapons/g_chain/skin.png','models/weapons/v_chain/skin.png')
BASELINES = {'view':{'triangles':1399,'position_vertices':692,'frames':1,'file_bytes':58968},
             'pickup':{'triangles':799,'position_vertices':392,'frames':1,'file_bytes':35768},
             'player':{'triangles':1545,'position_vertices':765,'frames':198,'file_bytes':676332},
             'enemy':{'triangles':1545,'position_vertices':765,'frames':475,'file_bytes':1535032}}
DEPENDENCIES = ('build_m60.py','m60_geometry.py','build_m16.py','m16_geometry.py')


def sha(data):
    return hashlib.sha256(data).hexdigest()


def texture_bytes():
    """Use the existing army-man plastic and painted mitten atlas unchanged."""
    return shared_texture_bytes()


def placement(role):
    rotation = np.eye(3)
    if role=='view':
        # Keep the existing two-handed rifle scale and comfortable hip pose.
        scale=(56.49812462925911+9.061456233263016)/100
        offset=np.array([-13.5,-9.,-7.2])
    elif role=='pickup':
        scale=.78
        rotation=np.diag([-1.,-1.,1.])
        offset=np.array([39.,0.,18.])
    else:
        # Preserve the army-man grip attachment and archived animation motion.
        scale=.31
        offset=np.array([10.2,-4.75,12.8])-np.asarray(GRIP)*scale
    return rotation*scale,offset,rotation


def ads_header(anchors):
    rear, muzzle = anchors['rear_sight'], anchors['muzzle']
    return ('''/* Generated by tools/assets/build_m60.py; model units only. */
#ifndef PP_M60_MODEL_ADS_H
#define PP_M60_MODEL_ADS_H
#define PP_M60_ADS_FORWARD (%sf)
#define PP_M60_ADS_RIGHT (%sf)
#define PP_M60_ADS_UP (%sf)
#define PP_M60_MUZZLE_FORWARD (%sf)
#define PP_M60_MUZZLE_RIGHT (%sf)
#define PP_M60_MUZZLE_UP (%sf)
#endif
''' % tuple(f'{v:.8f}' for v in (9.5-rear[0],rear[1],-rear[2],muzzle[0],-muzzle[1],muzzle[2]))).encode()


def build_assets():
    originals = json.loads((ROOT/'tools/assets/platoon-originals.json').read_text())
    meshes = {kind:build_m60(kind) for kind in ('world','view')}
    atlas = texture_bytes()
    assets = {path:atlas for path in TEXTURES}
    manifest = dict(schema=1, generator='tools/assets/build_m60.py',
        dependencies_sha256={p:sha((ROOT/'tools/assets'/p).read_bytes()) for p in DEPENDENCIES},
        source_archive=originals['source_archive'], method='authored closed primitives; archived rigid poses',
        hand='m16_geometry.add_hands; existing closed molded mittens and forearms',
        palette='Shared M16 army-man plastic and mitten atlas', models=[])
    for path, role in MODELS.items():
        motion_path = 'models/monsters/soldier/weapon_machinegun.md2' if role=='enemy' else path
        source = None if role=='pickup' else MD2.read(source_bytes(originals,'baseq2/'+motion_path),source_compat=True)
        mesh = meshes['view' if role == 'view' else 'world']
        matrix, offset, rotation = placement(role)
        posed = np.asarray(mesh['vertices']) @ matrix + offset
        directions = np.asarray(mesh['normals']) @ rotation
        fit = None
        if role in ('player','enemy'):
            rotations, offsets, errors = rigid_transforms(source)
            positions = np.asarray([posed @ r + t for r,t in zip(rotations,offsets)])
            normal_poses = np.asarray([directions @ r for r in rotations])
            names = source.names
            fit = dict(rms_max=float(f'{errors.max():.12g}'), frames=len(names))
        else:
            positions, normal_poses = posed[None], directions[None]
            names = ['frame_1'] if source is None else [source.names[0]]
        skin = TEXTURES[0] if role == 'pickup' else TEXTURES[1]
        raw, validation = encode_md2(positions, normal_poses, mesh['faces'],atlas_uvs(mesh),[skin],names)
        assets[path] = raw
        stats = MD2.read(raw).stats();stats.pop('frame_names')
        anchors = {name:(np.asarray(value) @ matrix + offset).tolist() for name,value in mesh['anchors'].items()}
        manifest['models'].append(dict(path=path, role=role, baseline=BASELINES.get(role), after=stats,
            pose_transfer=fit, validation=validation, anchors_frame0=anchors, parts=mesh['parts']))
    normal='models/monsters/soldier/weapon_heavy.md2'
    tall='models/monsters/soldier/tall/weapon_heavy.md2'
    height=json.loads(HEIGHT_CONFIG.read_text())
    assets[tall]=transform_model(assets[normal],height['scale'],height['foot_z'])
    stats=MD2.read(assets[tall]).stats();stats.pop('frame_names')
    manifest['models'].append(dict(path=tall,role='enemy_tall',baseline=BASELINES['enemy'],after=stats))
    enemy=next(m for m in manifest['models'] if m['role']=='enemy')
    body='models/monsters/soldier/tris.md2'
    if MD2.read((BASE/body).read_bytes()).names!=MD2.read(assets[normal]).names:
        raise ValueError('Enemy weapon and body pose names disagree')
    manifest['enemy_retarget']=dict(schema=1,model=normal,
        sources={'archived:models/monsters/soldier/weapon_machinegun.md2':sha(source_bytes(originals,'baseq2/models/monsters/soldier/weapon_machinegun.md2')),
                 'players/soldier/w_chaingun.md2':sha(assets['players/soldier/w_chaingun.md2']),
                 body:sha((BASE/body).read_bytes())},
        method='Original primitive M60 exported directly through archived enemy rigid attachment poses',
        frames=475,position_vertices=enemy['after']['position_vertices'],triangles=enemy['after']['triangles'],
        skin_references=enemy['after']['skin_references'],
        max_source_rigid_fit_error_units=enemy['pose_transfer']['rms_max'],
        max_output_quantization_error_units=enemy['validation']['max_vertex_quantization_error'],
        sha256=sha(assets[normal]),bytes=len(assets[normal]))
    anchors = next(m['anchors_frame0'] for m in manifest['models'] if m['role']=='view')
    header = ads_header(anchors)
    manifest['ads_header'] = dict(path=ADS_HEADER.relative_to(ROOT).as_posix(),sha256=sha(header))
    manifest['files'] = [dict(path=p,bytes=len(raw),sha256=sha(raw)) for p,raw in sorted(assets.items())]
    return assets, manifest, header


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--verify',action='store_true')
    args = parser.parse_args()
    assets, manifest, header = build_assets()
    outputs = {BASE/p:raw for p,raw in assets.items()}
    outputs[MANIFEST] = (json.dumps(manifest,indent=2)+'\n').encode()
    outputs[ADS_HEADER] = header
    outputs[HEAVY_MANIFEST] = (json.dumps(manifest['enemy_retarget'],indent=2)+'\n').encode()
    for path, raw in outputs.items():
        if args.verify:
            if not path.is_file() or path.read_bytes()!=raw:raise ValueError('Stale m60 output: '+str(path))
        elif not path.is_file() or path.read_bytes()!=raw:
            path.parent.mkdir(parents=True,exist_ok=True);path.write_bytes(raw)
    for model in manifest['models']:
        print(f"{model['role']}: {model['after']['triangles']} triangles, {model['after']['frames']} frames")
    print('Verified m60' if args.verify else 'Built M60; regenerate colors, height, muzzle points and package')


if __name__=='__main__':main()
