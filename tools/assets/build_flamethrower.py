#!/usr/bin/env python3
"""Build the flame wand, independently attached backpack and deforming hose."""
from __future__ import annotations
import argparse
import copy
import hashlib
import json
from pathlib import Path
import numpy as np
from asset_sources import source_bytes
from md2_assets import MD2
from md2_animation import repair_stale_triangle_table
from build_m16 import atlas_uvs, encode_md2, rigid_transforms, texture_bytes
from flamethrower_geometry import (build_flamethrower, build_backpack, hose_mesh,
                                  combine_meshes, GRIP, INLET, HOSE_CONTROLS)

ROOT = Path(__file__).resolve().parents[2]
BASE = ROOT / 'baseq2'
MANIFEST = ROOT / 'tools/assets/flamethrower-manifest.json'
ADS_HEADER = ROOT / 'src/client/header/flamethrower_model_ads.h'
MODELS = {'models/weapons/g_hyperb/tris.md2': 'pickup',
          'models/weapons/v_hyperb/tris.md2': 'view',
          'players/soldier/w_hyperblaster.md2': 'player'}
TEXTURES = ('models/weapons/g_hyperb/skin.png', 'models/weapons/v_hyperb/skin.png')
BASELINES = {'view': {'triangles':1799, 'position_vertices':901, 'frames':1, 'file_bytes':78144},
             'pickup': {'triangles':1199, 'position_vertices':572, 'frames':1, 'file_bytes':55020},
             'player': {'triangles':2493, 'position_vertices':1221, 'frames':198, 'file_bytes':1077852}}
DEPENDENCIES = ('build_flamethrower.py', 'flamethrower_geometry.py', 'build_m16.py',
                'm16_geometry.py', 'md2_animation.py')
SOURCE_HASH = '7742a95495ed3db8699798671bf42b635f97cbb0a74df6472fd4964479bf3e9a'
# These two complete, disjoint topological components were reviewed in the
# pinned original. Its GL commands, not its stale triangle table, are valid.
SOURCE_GROUPS = {'gun': (0, 284), 'backpack': (284, 1366)}


def sha(data):
    return hashlib.sha256(data).hexdigest()


def placement(role):
    rotation = np.eye(3)
    if role == 'view':
        scale = (56.49812462925911 + 9.061456233263016) / 100
        offset = np.array([-9., -8.5, -7.8])
    elif role == 'pickup':
        # The assembled body-space equipment is displayed as one pickup.
        scale = 1.9
        rotation = np.diag([-1., -1., 1.])
        offset = np.array([13.6, 0., -7.])
    else:
        scale = .30
        offset = np.array([10.2, -4.75, 12.8]) - np.asarray(GRIP) * scale
    return rotation * scale, offset, rotation


def placed(mesh, matrix, offset, rotation):
    result = dict(mesh)
    result['vertices'] = (np.asarray(mesh['vertices']) @ matrix + offset).tolist()
    result['normals'] = (np.asarray(mesh['normals']) @ rotation).tolist()
    result['anchors'] = {key: (np.asarray(value) @ matrix + offset).tolist()
                         for key, value in mesh['anchors'].items()}
    return result


def source_motion(originals):
    source, repair = repair_stale_triangle_table(
        source_bytes(originals, 'baseq2/players/soldier/w_hyperblaster.md2'),
        expected_sha256=SOURCE_HASH)
    motion = {}
    for name, (a, b) in SOURCE_GROUPS.items():
        selected = copy.copy(source)
        selected.positions = source.positions[:, a:b]
        rotation, translation, error = rigid_transforms(selected)
        motion[name] = (rotation, translation, error)
    return source, repair, motion


def build_assembled():
    gun = placed(build_flamethrower('world'), *placement('player'))
    pack = build_backpack()
    hose = hose_mesh(HOSE_CONTROLS, seed=(1., 0., 0.))
    mesh = combine_meshes((gun, pack, hose), 'world')
    return mesh, gun, pack, hose


def ads_header(anchors):
    rear, muzzle = anchors['rear_sight'], anchors['muzzle']
    values = (9.5-rear[0], rear[1], -rear[2], muzzle[0], -muzzle[1], muzzle[2])
    return ('''/* Generated by tools/assets/build_flamethrower.py; model units only. */
#ifndef PP_FLAMETHROWER_MODEL_ADS_H
#define PP_FLAMETHROWER_MODEL_ADS_H
#define PP_FLAMETHROWER_ADS_FORWARD (%sf)
#define PP_FLAMETHROWER_ADS_RIGHT (%sf)
#define PP_FLAMETHROWER_ADS_UP (%sf)
#define PP_FLAMETHROWER_MUZZLE_FORWARD (%sf)
#define PP_FLAMETHROWER_MUZZLE_RIGHT (%sf)
#define PP_FLAMETHROWER_MUZZLE_UP (%sf)
#endif
''' % tuple(f'{value:.8f}' for value in values)).encode()


def build_assets():
    originals = json.loads((ROOT/'tools/assets/platoon-originals.json').read_text())
    source, repair, motion = source_motion(originals)
    assembled, gun, pack, hose = build_assembled()
    view_hose = hose_mesh(((1., -11., -30.), (9., -10., -18.),
                           (22., -7., -12.), INLET), radius=1.4, detail='view')
    view = combine_meshes((build_flamethrower('view'), view_hose), 'view')
    assets = {path: texture_bytes() for path in TEXTURES}
    manifest = dict(schema=1, generator='tools/assets/build_flamethrower.py',
        dependencies_sha256={name:sha((ROOT/'tools/assets'/name).read_bytes()) for name in DEPENDENCIES},
        source_archive=originals['source_archive'], source_repair=repair,
        method='authored closed shapes; independent archived gun/backpack motion; endpoint-attached cubic hose',
        hand='m16_geometry.add_hands; exact existing molded mittens and forearms',
        palette='Shared M16 army-man plastic and mitten atlas', models=[])
    for path, role in MODELS.items():
        if role == 'view':
            mesh = placed(view, *placement('view'))
            positions, normals, names = np.asarray([mesh['vertices']]), np.asarray([mesh['normals']]), ['frame_1']
            transfer = None
        elif role == 'pickup':
            mesh = placed(assembled, *placement('pickup'))
            positions, normals, names = np.asarray([mesh['vertices']]), np.asarray([mesh['normals']]), ['frame_1']
            transfer = None
        else:
            mesh = assembled
            positions, normals = [], []
            gun_rot, gun_offset, _ = motion['gun']
            pack_rot, pack_offset, _ = motion['backpack']
            controls = np.asarray(HOSE_CONTROLS)
            for frame in range(len(source.names)):
                posed_controls = np.concatenate((controls[:2] @ pack_rot[frame] + pack_offset[frame],
                                                controls[2:] @ gun_rot[frame] + gun_offset[frame]))
                posed_hose = hose_mesh(posed_controls, seed=np.array([1.,0.,0.]) @ pack_rot[frame])
                positions.append(np.concatenate((np.asarray(gun['vertices']) @ gun_rot[frame] + gun_offset[frame],
                                                 np.asarray(pack['vertices']) @ pack_rot[frame] + pack_offset[frame],
                                                 posed_hose['vertices'])))
                normals.append(np.concatenate((np.asarray(gun['normals']) @ gun_rot[frame],
                                               np.asarray(pack['normals']) @ pack_rot[frame],
                                               posed_hose['normals'])))
            positions, normals, names = np.asarray(positions), np.asarray(normals), source.names
            transfer = {name: dict(vertices=list(SOURCE_GROUPS[name]), frames=len(source.names),
                                   rms_max=float(f'{values[2].max():.12g}')) for name,values in motion.items()}
            transfer['hose'] = dict(rings=8, sides=6, radius=.65,
                                   method='pack controls follow backpack; gun controls follow wand; transported rings')
        skin = TEXTURES[0] if role == 'pickup' else TEXTURES[1]
        raw, validation = encode_md2(positions, normals, mesh['faces'], atlas_uvs(mesh), [skin], names)
        assets[path] = raw
        stats = MD2.read(raw).stats(); stats.pop('frame_names')
        manifest['models'].append(dict(path=path, role=role, baseline=BASELINES[role], after=stats,
                                      pose_transfer=transfer, validation=validation,
                                      anchors_frame0=mesh['anchors'], parts=mesh['parts']))
    anchors = next(entry['anchors_frame0'] for entry in manifest['models'] if entry['role']=='view')
    header = ads_header(anchors)
    manifest['ads_header'] = dict(path=ADS_HEADER.relative_to(ROOT).as_posix(), sha256=sha(header))
    manifest['files'] = [dict(path=path, bytes=len(raw), sha256=sha(raw)) for path,raw in sorted(assets.items())]
    return assets, manifest, header


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--verify', action='store_true')
    args = parser.parse_args()
    assets, manifest, header = build_assets()
    outputs = {BASE/path:raw for path,raw in assets.items()}
    outputs[MANIFEST] = (json.dumps(manifest, indent=2)+'\n').encode()
    outputs[ADS_HEADER] = header
    for path, raw in outputs.items():
        if args.verify:
            if not path.is_file() or path.read_bytes()!=raw:
                raise ValueError('Stale flamethrower output: '+str(path))
        elif not path.is_file() or path.read_bytes()!=raw:
            path.parent.mkdir(parents=True, exist_ok=True); path.write_bytes(raw)
    for entry in manifest['models']:
        print(f"{entry['role']}: {entry['after']['triangles']} triangles, {entry['after']['frames']} frames")
    print('Verified flamethrower' if args.verify else 'Built flamethrower, backpack and attached hose')


if __name__=='__main__': main()
