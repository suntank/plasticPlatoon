#!/usr/bin/env python3
"""Build the side-by-side double-barrel shotgun, existing mittens, and every existing held pose."""
from __future__ import annotations
import argparse
import hashlib
import io
import json
import math
from pathlib import Path
import numpy as np
from PIL import Image, ImageDraw
from asset_sources import source_bytes
from md2_assets import MD2
from build_m16 import (atlas_uvs, encode_md2, rigid_transforms,
                       texture_bytes as shared_texture_bytes)
from sshotgun_geometry import build_sshotgun, GRIP

ROOT = Path(__file__).resolve().parents[2]
BASE = ROOT / 'baseq2'
MANIFEST = ROOT / 'tools/assets/sshotgun-manifest.json'
ADS_HEADER = ROOT / 'src/client/header/sshotgun_model_ads.h'
MODELS = {'models/weapons/g_shotg2/tris.md2':'pickup',
          'models/weapons/v_shotg2/tris.md2':'view',
          'players/soldier/w_sshotgun.md2':'player'}
TEXTURES = ('models/weapons/g_shotg2/skin.png','models/weapons/v_shotg2/skin.png')
BASELINES = {'view':{'triangles':1400,'position_vertices':697,'frames':1,'file_bytes':56816},
             'pickup':{'triangles':800,'position_vertices':397,'frames':1,'file_bytes':33968},
             'player':{'triangles':1510,'position_vertices':752,'frames':198,'file_bytes':662144}}
DEPENDENCIES = ('build_sshotgun.py','sshotgun_geometry.py','build_m16.py','m16_geometry.py','shotgun_parts.py')


def sha(data):
    return hashlib.sha256(data).hexdigest()


def texture_bytes():
    """Paint the twin tubes, molded side panels, checkering and sight bead."""
    atlas = Image.open(io.BytesIO(shared_texture_bytes())).convert('RGB')
    for tile_id in (4,5,6,11):
        tile = Image.new('RGB',(64,64))
        draw = ImageDraw.Draw(tile)
        for y in range(64):
            v = (y-4.5)/55
            if tile_id == 5:
                # A soft reflection on each cylindrical crown. The center
                # valley stays dark at small split-screen resolutions.
                light = (1+math.sin(math.tau*v))/2
                value = round(21+14*light+15*light**12)
                color = (round(.73*value),value,round(.36*value))
            elif tile_id == 11:
                color = (136-y//4,122-y//4,77-y//5)
            else:
                value = round((50 if tile_id == 6 else 40) - 9*y/63)
                color = (round(.73*value),value,round(.36*value))
            draw.line((0,y,63,y),fill=color)
        if tile_id == 5:
            # The tube UV midpoint is the junction between the rounded breech
            # and the long barrels. A narrow band accents each shoulder.
            for y in range(64):
                r,g,b = tile.getpixel((32,y))
                draw.point((32,y),fill=(r-7,g-7,b-7))
                draw.point((33,y),fill=(r+5,g+5,b+5))
        elif tile_id == 4:
            # A bounded checkered panel sits on either face of the fore-end.
            for y in range(19,47):
                margin = 11+abs(y-33)//2
                for x in range(margin,64-margin):
                    if (x+y)%8 == 0 or (x-y)%8 == 0:
                        tile.putpixel((x,y),(20,29,12))
        elif tile_id == 6:
            outline = [(9,38),(17,19),(44,19),(55,28),(51,43),(22,48),(9,38)]
            draw.line(outline,fill=(21,31,13),width=2)
            draw.line([(x,y+1) for x,y in outline[:4]],fill=(43,60,23))
            for x in (28,35):
                draw.line((x-5,36,x,28,x+6,32),fill=(54,69,31),width=2)
            for x,y in ((17,35),(48,30)):
                draw.ellipse((x-2,y-2,x+2,y+2),fill=(22,32,15))
                draw.point((x-1,y-1),fill=(54,67,31))
        atlas.paste(tile,(tile_id%4*64,tile_id//4*64))
    output = io.BytesIO()
    atlas.save(output,format='PNG',compress_level=9)
    return output.getvalue()


def placement(role):
    rotation = np.eye(3)
    if role=='view':
        # Lower the stock into the shoulder, exposing both barrel crowns.
        scale=(56.49812462925911+9.061456233263016)/100
        offset=np.array([-7.6,-7.2,-10.5])
    elif role=='pickup':
        scale=.44
        rotation=np.diag([-1.,-1.,1.])
        offset=np.array([22.,0.,17.])
    else:
        # Preserve the army-man grip attachment and archived animation motion.
        scale=.245
        offset=np.array([10.2,-4.75,12.8])-np.asarray(GRIP)*scale
    return rotation*scale,offset,rotation


def ads_header(anchors):
    rear, muzzle = anchors['rear_sight'], anchors['muzzle']
    return ('''/* Generated by tools/assets/build_sshotgun.py; model units only. */
#ifndef PP_SSHOTGUN_MODEL_ADS_H
#define PP_SSHOTGUN_MODEL_ADS_H
#define PP_SSHOTGUN_ADS_FORWARD (%sf)
#define PP_SSHOTGUN_ADS_RIGHT (%sf)
#define PP_SSHOTGUN_ADS_UP (%sf)
#define PP_SSHOTGUN_MUZZLE_FORWARD (%sf)
#define PP_SSHOTGUN_MUZZLE_RIGHT (%sf)
#define PP_SSHOTGUN_MUZZLE_UP (%sf)
#endif
''' % tuple(f'{v:.8f}' for v in (9.5-rear[0],rear[1],-rear[2],muzzle[0],-muzzle[1],muzzle[2]))).encode()


def build_assets():
    originals = json.loads((ROOT/'tools/assets/platoon-originals.json').read_text())
    meshes = {kind:build_sshotgun(kind) for kind in ('world','view')}
    atlas = texture_bytes()
    assets = {path:atlas for path in TEXTURES}
    manifest = dict(schema=1, generator='tools/assets/build_sshotgun.py',
        dependencies_sha256={p:sha((ROOT/'tools/assets'/p).read_bytes()) for p in DEPENDENCIES},
        source_archive=originals['source_archive'], method='authored closed primitives; archived rigid poses',
        hand='Shared right grip hand and a cupped support mitten fitted to the fore-end',
        palette='Army-man plastic with player-colored barrels, checkered fore-end and brass-colored bead', models=[])
    for path, role in MODELS.items():
        source = None if role == 'pickup' else MD2.read(source_bytes(originals,'baseq2/'+path),source_compat=True)
        mesh = meshes['view' if role == 'view' else 'world']
        matrix, offset, rotation = placement(role)
        posed = np.asarray(mesh['vertices']) @ matrix + offset
        directions = np.asarray(mesh['normals']) @ rotation
        fit = None
        if role=='player':
            rotations, offsets, errors = rigid_transforms(source)
            positions = np.asarray([posed @ r + t for r,t in zip(rotations,offsets)])
            normal_poses = np.asarray([directions @ r for r in rotations])
            names = source.names
            fit = dict(rms_max=float(f'{errors.max():.12g}'), frames=len(names))
        else:
            positions, normal_poses = posed[None], directions[None]
            names = ['frame_1'] if source is None else [source.names[0]]
        skin = TEXTURES[0] if role == 'pickup' else TEXTURES[1]
        raw, validation = encode_md2(positions, normal_poses, mesh['faces'],atlas_uvs(mesh),[skin],names)
        assets[path] = raw
        stats = MD2.read(raw).stats();stats.pop('frame_names')
        anchors = {name:(np.asarray(value) @ matrix + offset).tolist() for name,value in mesh['anchors'].items()}
        manifest['models'].append(dict(path=path, role=role, baseline=BASELINES.get(role), after=stats,
            pose_transfer=fit, validation=validation, anchors_frame0=anchors, parts=mesh['parts']))
    anchors = next(m['anchors_frame0'] for m in manifest['models'] if m['role']=='view')
    header = ads_header(anchors)
    manifest['ads_header'] = dict(path=ADS_HEADER.relative_to(ROOT).as_posix(),sha256=sha(header))
    manifest['files'] = [dict(path=p,bytes=len(raw),sha256=sha(raw)) for p,raw in sorted(assets.items())]
    return assets, manifest, header


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--verify',action='store_true')
    args = parser.parse_args()
    assets, manifest, header = build_assets()
    outputs = {BASE/p:raw for p,raw in assets.items()}
    outputs[MANIFEST] = (json.dumps(manifest,indent=2)+'\n').encode()
    outputs[ADS_HEADER] = header
    for path, raw in outputs.items():
        if args.verify:
            if not path.is_file() or path.read_bytes()!=raw:raise ValueError('Stale sshotgun output: '+str(path))
        elif not path.is_file() or path.read_bytes()!=raw:
            path.parent.mkdir(parents=True,exist_ok=True);path.write_bytes(raw)
    for model in manifest['models']:
        print(f"{model['role']}: {model['after']['triangles']} triangles, {model['after']['frames']} frames")
    print('Verified sshotgun' if args.verify else 'Built double-barrel shotgun; regenerate colors, muzzle points and package')


if __name__=='__main__':main()
