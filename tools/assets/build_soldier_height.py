#!/usr/bin/env python3
"""Build taller enemy soldier/attachment MD2s without changing authored meshes.

Only each frame's float scale/translation is transformed. Packed vertices,
normal indices, UVs, triangle/draw tables, skins and frame names remain exact.
Canonical source models stay untouched so their existing conversion manifests
and the player's model/weapon geometry remain reproducible.
"""
from __future__ import annotations

import argparse
import hashlib
import json
import math
from pathlib import Path
import struct

ROOT = Path(__file__).resolve().parents[2]
CONFIG = ROOT / 'tools/assets/soldier-height.json'
MANIFEST = ROOT / 'tools/assets/soldier-height-manifest.json'
HEADER = ROOT / 'src/common/header/soldier_dimensions.h'
MODELS = ('tris.md2', 'weapon_blaster.md2', 'weapon_shotgun.md2',
          'weapon_machinegun.md2', 'weapon_heavy.md2', 'weapon_rocket.md2')
MODEL_DIR = Path('models/monsters/soldier')
STANDING_FRAME = 146  # FRAME_stand101; frame zero is an attack pose.


def sha(data):
    return hashlib.sha256(data).hexdigest()


def transform_model(data, scale, foot_z):
    header = struct.unpack_from('<17i', data)
    if (header[0:2] != (844121161, 8) or header[16] != len(data)
            or header[4] != 40 + header[6] * 4):
        raise ValueError('expected compact, valid MD2 input')
    result = bytearray(data)
    for frame in range(header[10]):
        offset = header[14] + frame * header[4]
        values = struct.unpack_from('<6f', data, offset)
        scales = [v * scale for v in values[:3]]
        translate = [values[3] * scale, values[4] * scale,
                     foot_z + (values[5] - foot_z) * scale]
        struct.pack_into('<6f', result, offset, *scales, *translate)
    return bytes(result)


def frame_bounds(data, frame=0):
    header = struct.unpack_from('<17i', data)
    offset = header[14] + frame * header[4]
    values = struct.unpack_from('<6f', data, offset)
    vertices = [[data[offset + 40 + i * 4 + axis] * values[axis] + values[3 + axis]
                 for axis in range(3)] for i in range(header[6])]
    return [[min(v[a] for v in vertices), max(v[a] for v in vertices)] for a in range(3)]


def write_if_changed(path, data):
    if path.is_file() and path.read_bytes() == data:
        return
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_bytes(data)


def generate():
    config = json.loads(CONFIG.read_text())
    scale, foot = config['scale'], config['foot_z']
    if not 1 <= scale <= 2 or foot != -24:
        raise ValueError('review soldier collision and muzzle semantics before changing scale/foot anchor')
    body = (ROOT / 'baseq2' / MODEL_DIR / 'tris.md2').read_bytes()
    standing_head = frame_bounds(transform_model(body, scale, foot), STANDING_FRAME)[2][1]
    # The original hull had unused space above this project's shorter mesh.
    # Fit the corrected head rather than scaling that empty space: a 40-unit
    # top still fits existing 64-unit passages with the unchanged -24 feet.
    stand_max = float(math.ceil(standing_head))
    header = ('''/* Generated by tools/assets/build_soldier_height.py; do not edit. */
#ifndef PP_SOLDIER_DIMENSIONS_H
#define PP_SOLDIER_DIMENSIONS_H

/* Uniform MD2 scale anchored at the unchanged collision feet. */
#define PP_SOLDIER_MODEL_SCALE %sf
#define PP_SOLDIER_FOOT_Z %sf
#define PP_SOLDIER_XY(value) ((value) * PP_SOLDIER_MODEL_SCALE)
#define PP_SOLDIER_Z(value) (PP_SOLDIER_FOOT_Z + ((value) - PP_SOLDIER_FOOT_Z) * PP_SOLDIER_MODEL_SCALE)
#define PP_SOLDIER_STAND_MAX_Z %sf
#define PP_SOLDIER_DUCK_MAX_Z PP_SOLDIER_Z(0.0f)
/* edict viewheight is integral; round the transformed eye points. */
#define PP_SOLDIER_STAND_VIEW_Z ((int)(PP_SOLDIER_Z(25.0f) + 0.5f))
#define PP_SOLDIER_DUCK_VIEW_Z ((int)(PP_SOLDIER_Z(0.0f) + 0.5f))
#define PP_SOLDIER_DUCK_DROP (PP_SOLDIER_STAND_MAX_Z - PP_SOLDIER_DUCK_MAX_Z)
#define PP_SOLDIER_DEAD_MAX_Z PP_SOLDIER_Z(-8.0f)

#endif
''' % (repr(float(scale)), repr(float(foot)), repr(stand_max))).encode()
    outputs = {HEADER: header}
    manifest = dict(schema=1, scale=scale, foot_z=foot, standing_frame=STANDING_FRAME,
                    standing_head_z=standing_head, standing_hull_max_z=stand_max,
                    generator_sha256=sha(Path(__file__).read_bytes()),
                    config_sha256=sha(CONFIG.read_bytes()), models=[])
    for filename in MODELS:
        source = ROOT / 'baseq2' / MODEL_DIR / filename
        relative = MODEL_DIR / 'tall' / filename
        destination = ROOT / 'baseq2' / relative
        raw = source.read_bytes()
        generated = transform_model(raw, scale, foot)
        outputs[destination] = generated
        manifest['models'].append(dict(
            source=source.relative_to(ROOT / 'baseq2').as_posix(),
            source_sha256=sha(raw), output=relative.as_posix(),
            sha256=sha(generated), bytes=len(generated),
            standing_bounds_before=frame_bounds(raw, STANDING_FRAME),
            standing_bounds_after=frame_bounds(generated, STANDING_FRAME)))
    manifest['dimension_header'] = dict(path=HEADER.relative_to(ROOT).as_posix(), sha256=sha(header))
    outputs[MANIFEST] = (json.dumps(manifest, indent=2) + '\n').encode()
    return outputs


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--verify', action='store_true')
    args = parser.parse_args()
    outputs = generate()
    for path, data in outputs.items():
        if args.verify:
            if not path.is_file() or path.read_bytes() != data:
                raise ValueError(f'soldier height output differs from reproducible build: {path}')
        else:
            write_if_changed(path, data)
    config = json.loads(CONFIG.read_text())
    print(f"{'Verified' if args.verify else 'Built'} six taller soldier/weapon models "
          f"at {config['scale']}x, feet anchored at {config['foot_z']}")


if __name__ == '__main__':
    main()
