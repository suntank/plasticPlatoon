#!/usr/bin/env python3
"""Build the long beveled pistol, fitted mitten, and every existing held pose."""
from __future__ import annotations
import argparse
import hashlib
import io
import json
import math
from pathlib import Path
import numpy as np
from PIL import Image, ImageDraw
from asset_sources import source_bytes
from md2_assets import MD2
from build_m16 import (atlas_uvs, encode_md2, rigid_transforms,
                       texture_bytes as shared_texture_bytes, COLORS, ALBEDO_SCALE)
from build_soldier_height import transform_model, CONFIG as HEIGHT_CONFIG
from pistol_geometry import build_pistol, GRIP

ROOT = Path(__file__).resolve().parents[2]
BASE = ROOT / 'baseq2'
MANIFEST = ROOT / 'tools/assets/pistol-manifest.json'
ADS_HEADER = ROOT / 'src/client/header/pistol_model_ads.h'
MODELS = {'models/weapons/g_blast/tris.md2':'pickup',
          'models/weapons/v_blast/tris.md2':'view',
          'players/soldier/w_blaster.md2':'player',
          'models/monsters/soldier/weapon_blaster.md2':'enemy'}
TEXTURES = ('models/weapons/g_blast/skin.png','models/weapons/v_blast/skin.png')
BASELINES = {'view':{'triangles':1400,'position_vertices':700,'frames':1,'file_bytes':56768},
             'player':{'triangles':1580,'position_vertices':790,'frames':198,'file_bytes':694880},
             'enemy':{'triangles':1616,'position_vertices':808,'frames':475,'file_bytes':1616844}}
DEPENDENCIES = ('build_pistol.py','pistol_geometry.py','build_m16.py','m16_geometry.py')


def sha(data):
    return hashlib.sha256(data).hexdigest()


def texture_bytes():
    """M16 plastic palette, with local rear serrations and soft finger creases."""
    atlas = Image.open(io.BytesIO(shared_texture_bytes())).convert('RGB')
    for index in (4,10):
        rgb = COLORS[index]
        tile = Image.new('RGB',(64,64))
        for y in range(64):
            for x in range(64):
                shading = .93+.10*(1-y/63)+.025*math.sin(x*math.pi/63)
                tile.putpixel((x,y),tuple(round(round(c*shading)*ALBEDO_SCALE) for c in rgb))
        draw = ImageDraw.Draw(tile)
        base = tuple(round(c*ALBEDO_SCALE) for c in rgb)
        shadow = tuple(round(c*.83) for c in base)
        highlight = tuple(round(c*1.06) for c in base)
        if index == 4:
            # Four fine molded serrations at the rear, leaving the long slide clean.
            for x in (9,13,17,21):
                draw.line((x,14,x,49),fill=shadow,width=1)
                draw.line((x+1,15,x+1,48),fill=highlight,width=1)
        else:
            # Creases live on the fused fingers, not as rings around the palm.
            for y in (20,32,44):
                draw.line((16,y,30,y+2,46,y),fill=shadow,width=1)
                draw.line((18,y+2,30,y+3,44,y+2),fill=highlight,width=1)
        atlas.paste(tile,(index%4*64,index//4*64))
    output = io.BytesIO();atlas.save(output,format='PNG',compress_level=9)
    return output.getvalue()


def placement(role):
    rotation = np.eye(3)
    if role == 'view':
        # Keep the established army-man scale. The pistol's hand is posed
        # high around its own grip instead of inheriting the rifle's pose.
        scale = (56.49812462925911 + 9.061456233263016) / 100
        offset = np.array([24 - 25.7 * scale, -8.8, -1.2 - 7.0 * scale])
    elif role == 'pickup':
        scale = .55
        rotation = np.diag([-1.,-1.,1.])
        offset = np.array([41.4 * scale,0.,11.2 * scale + 5])
    else:
        # Preserve the previous held grip center as the anchor, letting the
        # longer muzzle move with the new silhouette. Archived rigid motion
        # supplies every subsequent player/enemy position and rotation.
        scale = (14.83447005 - 7.58781338) / (52.5 - 25.5)
        old_offset = np.array([14.83447005 - 52.5 * scale, -4.99334933,
                               15.49516889 - 3.6 * scale])
        old_grip = np.array([32.,0.,-8.])*scale+old_offset
        offset = old_grip-np.asarray(GRIP)*scale
    return rotation * scale, offset, rotation


def ads_header(anchors):
    rear, muzzle = anchors['rear_sight'], anchors['muzzle']
    return ('''/* Generated by tools/assets/build_pistol.py; model units only. */
#ifndef PP_PISTOL_MODEL_ADS_H
#define PP_PISTOL_MODEL_ADS_H
#define PP_PISTOL_ADS_FORWARD (%sf)
#define PP_PISTOL_ADS_RIGHT (%sf)
#define PP_PISTOL_ADS_UP (%sf)
#define PP_PISTOL_MUZZLE_FORWARD (%sf)
#define PP_PISTOL_MUZZLE_RIGHT (%sf)
#define PP_PISTOL_MUZZLE_UP (%sf)
#endif
''' % tuple(f'{v:.8f}' for v in (9.5-rear[0],rear[1],-rear[2],muzzle[0],-muzzle[1],muzzle[2]))).encode()


def build_assets():
    originals = json.loads((ROOT/'tools/assets/platoon-originals.json').read_text())
    meshes = {kind:build_pistol(kind) for kind in ('world','view')}
    atlas = texture_bytes()
    assets = {path:atlas for path in TEXTURES}
    manifest = dict(schema=1, generator='tools/assets/build_pistol.py',
        dependencies_sha256={p:sha((ROOT/'tools/assets'/p).read_bytes()) for p in DEPENDENCIES},
        source_archive=originals['source_archive'], method='authored closed primitives; archived rigid poses',
        hand='pistol_geometry.add_pistol_hand; exterior grip wrap, curled finger bank and continuous wrist',
        palette='M16 plastic values; pistol-local rear serrations and finger creases', models=[])
    for path, role in MODELS.items():
        source = None if role == 'pickup' else MD2.read(source_bytes(originals,'baseq2/'+path),source_compat=True)
        mesh = meshes['view' if role == 'view' else 'world']
        matrix, offset, rotation = placement(role)
        posed = np.asarray(mesh['vertices']) @ matrix + offset
        directions = np.asarray(mesh['normals']) @ rotation
        fit = None
        if role in ('player','enemy'):
            rotations, offsets, errors = rigid_transforms(source)
            positions = np.asarray([posed @ r + t for r,t in zip(rotations,offsets)])
            normal_poses = np.asarray([directions @ r for r in rotations])
            names = source.names
            fit = dict(rms_max=float(f'{errors.max():.12g}'), frames=len(names))
        else:
            positions, normal_poses = posed[None], directions[None]
            names = ['frame_1'] if source is None else [source.names[0]]
        skin = TEXTURES[0] if role == 'pickup' else TEXTURES[1]
        raw, validation = encode_md2(positions, normal_poses, mesh['faces'],atlas_uvs(mesh),[skin],names)
        assets[path] = raw
        stats = MD2.read(raw).stats();stats.pop('frame_names')
        anchors = {name:(np.asarray(value) @ matrix + offset).tolist() for name,value in mesh['anchors'].items()}
        manifest['models'].append(dict(path=path, role=role, baseline=BASELINES.get(role), after=stats,
            pose_transfer=fit, validation=validation, anchors_frame0=anchors, parts=mesh['parts']))
    normal = 'models/monsters/soldier/weapon_blaster.md2'
    tall = 'models/monsters/soldier/tall/weapon_blaster.md2'
    height = json.loads(HEIGHT_CONFIG.read_text())
    assets[tall] = transform_model(assets[normal],height['scale'],height['foot_z'])
    stats = MD2.read(assets[tall]).stats();stats.pop('frame_names')
    manifest['models'].append(dict(path=tall,role='enemy_tall',baseline=BASELINES['enemy'],after=stats))
    anchors = next(m['anchors_frame0'] for m in manifest['models'] if m['role']=='view')
    header = ads_header(anchors)
    manifest['ads_header'] = dict(path=ADS_HEADER.relative_to(ROOT).as_posix(),sha256=sha(header))
    manifest['files'] = [dict(path=p,bytes=len(raw),sha256=sha(raw)) for p,raw in sorted(assets.items())]
    return assets, manifest, header


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--verify',action='store_true')
    args = parser.parse_args()
    assets, manifest, header = build_assets()
    outputs = {BASE/p:raw for p,raw in assets.items()}
    outputs[MANIFEST] = (json.dumps(manifest,indent=2)+'\n').encode()
    outputs[ADS_HEADER] = header
    for path, raw in outputs.items():
        if args.verify:
            if not path.is_file() or path.read_bytes()!=raw:raise ValueError('Stale pistol output: '+str(path))
        elif not path.is_file() or path.read_bytes()!=raw:
            path.parent.mkdir(parents=True,exist_ok=True);path.write_bytes(raw)
    for model in manifest['models']:
        print(f"{model['role']}: {model['after']['triangles']} triangles, {model['after']['frames']} frames")
    print('Verified pistol' if args.verify else 'Built pistol; regenerate colors, height, muzzle points and package')


if __name__=='__main__':main()
